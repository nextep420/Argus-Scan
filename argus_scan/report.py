"""Report generation: JSON, CSV, and a self-contained HTML report with inlined CSS."""

from __future__ import annotations

import csv
import io
import json
from datetime import datetime, timezone


def build_report_data(scan_results: list, enrichments: dict) -> dict:
    """Assemble a plain-dict report from scan results plus enrichment data keyed by "target:port"."""
    report = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "tool": "Argus",
        "hosts": [],
    }

    for res in scan_results:
        host_entry = {
            "target": res.target,
            "resolved_ip": res.resolved_ip,
            "host_up": res.host_up,
            "elapsed_seconds": res.elapsed_seconds,
            "closed_count": res.closed_count,
            "filtered_count": res.filtered_count,
            "open_ports": [],
        }
        for p in res.open_ports:
            key = f"{res.target}:{p.port}"
            enrich = enrichments.get(key, {})
            port_entry = {
                "port": p.port,
                "service": p.service,
                "banner": p.banner,
                "latency_ms": p.latency_ms,
                **enrich,
            }
            host_entry["open_ports"].append(port_entry)
        report["hosts"].append(host_entry)

    return report


def to_json(report: dict) -> str:
    return json.dumps(report, indent=2, default=str)


def to_csv(report: dict) -> str:
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(["target", "ip", "port", "service", "banner", "latency_ms", "vulnerabilities"])
    for host in report["hosts"]:
        for p in host["open_ports"]:
            vulns = p.get("vulnerabilities", [])
            vuln_str = "; ".join(v["cve"] for v in vulns) if vulns else ""
            writer.writerow([
                host["target"], host["resolved_ip"], p["port"],
                p.get("service") or "", p.get("banner") or "",
                p.get("latency_ms") or "", vuln_str,
            ])
    return buf.getvalue()


