_HOST_TEMPLATE = """
<div class="host">
  <h2>{target} <span class="ip">({resolved_ip})</span></h2>
  <div class="stats">
    <span>{open_count} open</span>
    <span>{closed_count} closed</span>
    <span>{filtered_count} filtered</span>
    <span>{elapsed}s elapsed</span>
  </div>
  {ports_table}
</div>"""


def _severity_badge(sev: str) -> str:
    return f'<span class="badge sev-{sev}">{sev.upper()}</span>'


def to_html(report: dict) -> str:
    hosts_html = []
    for host in report["hosts"]:
        if not host["open_ports"]:
            ports_table = '<div class="no-ports">No open ports found.</div>'
        else:
            rows = []
            for p in host["open_ports"]:
                vulns = p.get("vulnerabilities", [])
                vuln_html = "<br>".join(
                    f'{_severity_badge(v["severity"])} {v["cve"]}: {v["summary"]}'
                    for v in vulns
                ) if vulns else "&mdash;"
                service = p.get("service") or "unknown"
                banner = (p.get("banner") or "")[:80]
                rows.append(
                    f"<tr><td>{p['port']}</td><td>{service}</td>"
                    f"<td>{banner}</td><td>{vuln_html}</td></tr>"
                )
            ports_table = (
                "<table><tr><th>Port</th><th>Service</th><th>Banner</th>"
                "<th>Known Vulnerabilities</th></tr>" + "".join(rows) + "</table>"
            )

        hosts_html.append(_HOST_TEMPLATE.format(
            target=host["target"],
            resolved_ip=host["resolved_ip"] or "unresolved",
            open_count=len(host["open_ports"]),
            closed_count=host["closed_count"],
            filtered_count=host["filtered_count"],
            elapsed=host["elapsed_seconds"],
            ports_table=ports_table,
        ))

    return _HTML_TEMPLATE.format(
        generated_at=report["generated_at"],
        hosts_html="".join(hosts_html),
    )
